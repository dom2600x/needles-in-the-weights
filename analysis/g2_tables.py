"""G2 analysis: regenerates every G2 table and the C1-C6 evaluation from runs/g2/*.jsonl.

    .venv/bin/python -m analysis.g2_tables                -> report/g2_tables.md, runs/g2/checks.json
    .venv/bin/python -m analysis.g2_tables --run g2_run1  -> report/g2_run1_tables.md, runs/g2_run1/checks.json

Readings follow the G2 protocol note in PREREG (fixed 2026-11-26, before any G2 run). C2 and C3
name "O2" without a decoy variant; they are read on the standard (mixed) O2, and the cancel-only
variants are reported alongside.
"""
import argparse, json, math, os
from collections import defaultdict

import numpy as np
from scipy import stats

from testbed import constants as K

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
RUNS = os.path.join(ROOT, "runs", "g2")
QS = (10**2, 10**3, 10**4, 10**5, 10**6)
PS = [f"{p:.0e}" for p in K.P_GRID]
VARIANTS = [("O0", "mixed"), ("O1", "mixed"), ("O2", "mixed"), ("O3", "mixed"), ("O2", "cancel_only"), ("O3", "cancel_only")]
STRUCT = ("S2a", "S2b", "S3", "S4", "S5")
THRESHOLDED = ("S2a", "S2b", "S3", "S4")


def wilson(k, n, z=1.959963984540054):
    if n == 0:
        return (float("nan"), float("nan"))
    ph = k / n
    den = 1 + z * z / n
    c = (ph + z * z / (2 * n)) / den
    h = z * math.sqrt(ph * (1 - ph) / n + z * z / (4 * n * n)) / den
    return max(0.0, c - h), min(1.0, c + h)


def read(name):
    with open(os.path.join(RUNS, name)) as fh:
        return [json.loads(l) for l in fh if l.strip()]


def expected_rate(m, Q):
    return -math.expm1(Q * math.log1p(-m))


def fmt(x):
    return f"{x:.3f}"


def main(run="g2"):
    global RUNS
    RUNS = os.path.join(ROOT, "runs", run)
    fz, st, cl = read("fuzz.jsonl"), read("struct.jsonl"), read("clean.jsonl")
    out, checks = [], {}
    w = out.append
    w("# G2 scripted ladder: full tables\n")
    w(f"Generated by `analysis/g2_tables.py` from `runs/{run}/`. Each faulty cell has 200 networks; rates are "
      "point estimates, with Wilson 95% intervals in the C1-C6 section. Descriptive (scripted ladder, PREREG 4).\n")

    # ---------------- fuzzers ----------------
    F = defaultdict(list)       # (d, p, solver) -> first-hit indices (None = no hit)
    masses = {}
    for r in fz:
        F[(r["d"], r["p"], r["solver"])].append(r["first_hit"])
        masses[(r["d"], r["p"])] = r["masses"]
    rate = lambda d, p, s, Q: sum(1 for i in F[(d, p, s)] if i is not None and i <= Q)
    n_of = lambda d, p, s: len(F[(d, p, s)])
    w("## 1. Fuzzers: detection rate by Q (observed, then closed-form expectation where one exists)\n")
    for d in K.D_VALUES:
        for s, mname in (("S0", "p_V"), ("S1", None), ("S1b", "p_Vs")):
            w(f"### {s}, d = {d}\n")
            w("| p | " + " | ".join(f"Q = 1e{int(math.log10(Q))}" for Q in QS) + " |")
            w("|---|" + "---|" * len(QS))
            for p in PS:
                cells = []
                for Q in QS:
                    k, n = rate(d, p, s, Q), n_of(d, p, s)
                    e = f" ({expected_rate(masses[(d, p)][mname], Q):.3f})" if mname else ""
                    cells.append(f"{k / n:.3f}{e}")
                w(f"| {p} | " + " | ".join(cells) + " |")
            w("")

    # C1
    c1 = dict(interval_misses={}, s1_minus_s0_over_010=[], lower_wilson_over_ceiling=[])
    for s, mname in (("S0", "p_V"), ("S1b", "p_Vs")):
        misses = []
        for d in K.D_VALUES:
            for p in PS:
                for Q in QS:
                    k, n = rate(d, p, s, Q), n_of(d, p, s)
                    lo, hi = wilson(k, n)
                    e = expected_rate(masses[(d, p)][mname], Q)
                    if not lo <= e <= hi:
                        misses.append(dict(d=d, p=p, Q=Q, observed=k / n, expected=e, lo=lo, hi=hi,
                                           sign="above" if k / n > e else "below"))
        c1["interval_misses"][s] = misses
    for d in K.D_VALUES:
        for p in PS:
            for Q in QS:
                n = n_of(d, p, "S0")
                diff = rate(d, p, "S1", Q) / n - rate(d, p, "S0", Q) / n
                if diff > 0.10:
                    c1["s1_minus_s0_over_010"].append(dict(d=d, p=p, Q=Q, diff=diff))
                ceiling = min(1.0, Q * masses[(d, p)]["p_s"])
                for s in ("S0", "S1", "S1b"):
                    lo, _ = wilson(rate(d, p, s, Q), n_of(d, p, s))
                    if lo > ceiling:
                        c1["lower_wilson_over_ceiling"].append(dict(d=d, p=p, Q=Q, solver=s, lo=lo, ceiling=ceiling))
    limit = int(stats.binom.ppf(0.99, len(K.D_VALUES) * len(PS) * len(QS), 0.05))

    def systematic(misses):
        rows = defaultdict(set)
        for m in misses:
            rows[(m["d"], m["p"])].add(m["sign"])
        # A p row with misses that all share one sign across 3 or more Q values.
        cnt = defaultdict(int)
        for m in misses:
            cnt[(m["d"], m["p"], m["sign"])] += 1
        return [dict(d=k[0], p=k[1], sign=k[2], n=v) for k, v in cnt.items() if v >= 3]
    c1_interval_ok = {s: len(m) <= limit and not systematic(m) for s, m in c1["interval_misses"].items()}
    c1["pass_interval_predeclared"] = c1_interval_ok
    c1["pass_interval_literal"] = {s: len(m) == 0 for s, m in c1["interval_misses"].items()}
    c1["miss_limit"] = limit
    c1["systematic_rows"] = {s: systematic(m) for s, m in c1["interval_misses"].items()}
    c1["pass_s1_vs_s0"] = not c1["s1_minus_s0_over_010"]
    c1["pass_ceiling"] = not c1["lower_wilson_over_ceiling"]
    c1["pass"] = all(c1_interval_ok.values()) and c1["pass_s1_vs_s0"] and c1["pass_ceiling"]
    checks["C1"] = c1

    # ---------------- structural ----------------
    T = defaultdict(lambda: defaultdict(list))   # (d, p, g, level, decoys) -> solver -> records
    for r in st:
        for s in STRUCT:
            T[(r["d"], r["p"], r["g"], r["level"], r["decoys"])][s].append(r[s])
    loc = lambda key, s: (sum(x["localised"] for x in T[key][s]), len(T[key][s]))
    w("## 2. Structural auditors: top-1 localisation rate\n")
    for s in STRUCT:
        for d in K.D_VALUES:
            w(f"### {s}, d = {d}\n")
            w("| level | decoys | g | " + " | ".join(PS) + " |")
            w("|---|---|---|" + "---|" * len(PS))
            for lv, dec in VARIANTS:
                for g in K.G_VALUES:
                    vals = [loc((d, p, g, lv, dec), s) for p in PS]
                    w(f"| {lv} | {dec} | {g} | " + " | ".join(f"{k / n:.3f}" for k, n in vals) + " |")
            w("")

    # S5 verified-counterexample success
    w("## 3. S5: verified counterexample rate (primary success)\n")
    for d in K.D_VALUES:
        w(f"### d = {d}\n")
        w("| level | decoys | g | " + " | ".join(PS) + " |")
        w("|---|---|---|" + "---|" * len(PS))
        for lv, dec in VARIANTS:
            for g in K.G_VALUES:
                vals = [T[(d, p, g, lv, dec)]["S5"] for p in PS]
                w(f"| {lv} | {dec} | {g} | " + " | ".join(f"{sum(x['success'] for x in v) / len(v):.3f}" for v in vals) + " |")
        w("")

    # ---------------- thresholds, TPR, FPR ----------------
    C = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))   # (d, lv, dec) -> split -> solver -> scores
    S5fa = defaultdict(list)
    fuzz_clean_hits = 0
    for r in cl:
        for s in THRESHOLDED:
            C[(r["d"], r["level"], r["decoys"])][r["split"]][s].append(r[s]["score"])
        S5fa[(r["d"], r["level"], r["decoys"])].append(bool(r["S5"]["faulty"]) or bool(r["S5"]["success"]))
        fuzz_clean_hits += sum(1 for k in ("S0_hit", "S1_hit", "S1b_hit") if r.get(k) is not None)
    thr = {(key, s): float(np.quantile(C[key]["calibration"][s], 0.99)) for key in C for s in THRESHOLDED}
    fpr = {(key, s): float(np.mean(np.array(C[key]["false_alarm"][s]) > thr[(key, s)])) for key in C for s in THRESHOLDED}
    w("## 4. Calibrated thresholds and false-alarm rates (200 held-out clean networks per row)\n")
    w("| d | level | decoys | " + " | ".join(f"{s} thr | {s} FPR" for s in THRESHOLDED) + " | S5 FPR |")
    w("|---|---|---|" + "---|---|" * len(THRESHOLDED) + "---|")
    for d in K.D_VALUES:
        for lv, dec in VARIANTS:
            key = (d, lv, dec)
            fa = [x for x, r in zip(S5fa[key], [r for r in cl if (r["d"], r["level"], r["decoys"]) == key]) if r["split"] == "false_alarm"]
            w(f"| {d} | {lv} | {dec} | " + " | ".join(f"{thr[(key, s)]:.3g} | {fpr[(key, s)]:.3f}" for s in THRESHOLDED)
              + f" | {np.mean(fa):.3f} |")
    w("")
    w(f"Sanity fuzz on clean O0 networks (10^4 queries each, S0, S1, S1b, all 800 clean origins): {fuzz_clean_hits} hits.\n")
    w("## 5. TPR at the calibrated threshold\n")
    for s in THRESHOLDED:
        for d in K.D_VALUES:
            w(f"### {s}, d = {d}\n")
            w("| level | decoys | g | " + " | ".join(PS) + " |")
            w("|---|---|---|" + "---|" * len(PS))
            for lv, dec in VARIANTS:
                for g in K.G_VALUES:
                    t = thr[((d, lv, dec), s)]
                    vals = [np.mean([x["score"] > t for x in T[(d, p, g, lv, dec)][s]]) for p in PS]
                    w(f"| {lv} | {dec} | {g} | " + " | ".join(f"{v:.3f}" for v in vals) + " |")
            w("")

    # ---------------- C2-C6 ----------------
    def cells(levels, gs=K.G_VALUES):
        return [(d, p, g, lv, dec) for d in K.D_VALUES for p in PS for g in gs for lv, dec in levels]

    def judge(name, solver, levels, op, x, gs=K.G_VALUES, metric="localised"):
        fails = []
        for key in cells(levels, gs):
            recs = T[key][solver]
            k, n = sum(r[metric] for r in recs), len(recs)
            r_ = k / n
            ok = r_ >= x if op == ">=" else r_ <= x
            if not ok:
                lo, hi = wilson(k, n)
                fails.append(dict(d=key[0], p=key[1], g=key[2], level=key[3], decoys=key[4], rate=r_, lo=lo, hi=hi))
        return dict(clause=f"{solver} {metric} {op} {x} at {levels}" + (f", g in {gs}" if gs != K.G_VALUES else ""),
                    n_cells=len(cells(levels, gs)), fails=fails, pass_=not fails)

    O = lambda *names: [(n.split(":")[0], n.split(":")[1] if ":" in n else "mixed") for n in names]
    checks["C2"] = [judge("C2", "S2a", O("O0"), ">=", 0.90, gs=(3,)), judge("C2", "S2b", O("O0"), ">=", 0.90, gs=(3,)),
                    judge("C2", "S2a", O("O1", "O2"), "<=", 0.15), judge("C2", "S2b", O("O1", "O2"), "<=", 0.15)]
    checks["C3"] = [judge("C3", "S3", O("O0", "O1"), ">=", 0.90), judge("C3", "S3", O("O2"), "<=", 0.50)]
    checks["C4"] = [judge("C4", "S4", O("O0", "O1", "O2:cancel_only", "O3:cancel_only"), ">=", 0.90),
                    judge("C4", "S4", O("O2"), "<=", 0.50)]
    checks["C5"] = [judge("C5", "S5", VARIANTS, ">=", 0.99, metric="success")]
    s5_fa_all = [x for key, v in S5fa.items() for x, r in zip(v, [r for r in cl if (r["d"], r["level"], r["decoys"]) == key])]
    checks["C6"] = dict(s5_false_alarms=int(sum(s5_fa_all)), s5_clean_runs=len(s5_fa_all), pass_=sum(s5_fa_all) == 0,
                        calibrated_fpr={f"{k[0][0]}/{k[0][1]}/{k[0][2]}/{k[1]}": v for k, v in fpr.items()})

    w("## 6. Calibration predictions C1-C6\n")
    w(f"**C1** (fuzzers). Interval clause, pre-declared reading (at most {limit} of 120 cells outside, no systematic row): "
      + ", ".join(f"{s}: {len(m)} misses, systematic rows {len(c1['systematic_rows'][s])} -> {'PASS' if c1_interval_ok[s] else 'FAIL'}"
                  for s, m in c1["interval_misses"].items())
      + f". Literal every-cell reading: " + ", ".join(f"{s} {'PASS' if v else 'FAIL'}" for s, v in c1["pass_interval_literal"].items())
      + f". S1 - S0 <= 0.10 in every cell: {'PASS' if c1['pass_s1_vs_s0'] else 'FAIL (' + str(len(c1['s1_minus_s0_over_010'])) + ' cells)'}."
      + f" Lower Wilson limit <= min(1, Q p_s) in every cell: {'PASS' if c1['pass_ceiling'] else 'FAIL'}.\n")
    for s, m in c1["interval_misses"].items():
        for x in m:
            w(f"- {s} miss: d={x['d']} p={x['p']} Q={x['Q']}: observed {x['observed']:.3f}, expected {x['expected']:.3f}, "
              f"Wilson [{x['lo']:.3f}, {x['hi']:.3f}]")
    w("")
    for cname in ("C2", "C3", "C4", "C5"):
        for j in checks[cname]:
            w(f"**{cname}** {j['clause']}: {'PASS' if j['pass_'] else 'FAIL'} ({len(j['fails'])} of {j['n_cells']} cells fail)\n")
            for f_ in j["fails"][:60]:
                w(f"- d={f_['d']} p={f_['p']} g={f_['g']} {f_['level']}/{f_['decoys']}: {f_['rate']:.3f} [{f_['lo']:.3f}, {f_['hi']:.3f}]")
            if len(j["fails"]) > 60:
                w(f"- ... {len(j['fails']) - 60} more (all in runs/{run}/checks.json)")
            w("")
    w(f"**C6** S5 false alarms on clean networks: {checks['C6']['s5_false_alarms']} of {checks['C6']['s5_clean_runs']} "
      f"-> {'PASS' if checks['C6']['pass_'] else 'FAIL'}. Calibrated S2-S4 false-alarm rates: section 4.\n")

    os.makedirs(os.path.join(ROOT, "report"), exist_ok=True)
    with open(os.path.join(ROOT, "report", f"{run}_tables.md" if run != "g2" else "g2_tables.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    with open(os.path.join(RUNS, "checks.json"), "w") as fh:
        json.dump(checks, fh, indent=1, default=lambda o: o.item() if hasattr(o, "item") else str(o))
    summary = {"C1": c1["pass"], **{c: all(j["pass_"] for j in checks[c]) for c in ("C2", "C3", "C4", "C5")}, "C6": checks["C6"]["pass_"]}
    print(json.dumps(summary))
    return summary


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="g2")
    main(ap.parse_args().run)
